export function languageForUrl(value) {
  return new URL(value).searchParams.get('lang') === 'en' ? 'en' : 'zh';
}

export function languageHref(value, language) {
  const url = new URL(value);
  url.searchParams.set('lang', language === 'en' ? 'en' : 'zh');
  return url.pathname + url.search + url.hash;
}

